import { describe, expect, it } from 'vitest'
import { isJpHoliday } from '../jp-holidays'

// 内閣府の公式一覧（振替休日・国民の休日を含む）。2026・2027 年は「国民の祝日について」のページ、
// 2022〜2025 年は syukujitsu.csv から。CSV の取り出しで 1 月 1 日の行が落ちたため、法律で日付が
// 固定されている元日だけ補っている
const OFFICIAL: Record<number, string[]> = {
  2022: ['01-01', '01-10', '02-11', '02-23', '03-21', '04-29', '05-03', '05-04', '05-05', '07-18',
    '08-11', '09-19', '09-23', '10-10', '11-03', '11-23'],
  2023: ['01-01', '01-02', '01-09', '02-11', '02-23', '03-21', '04-29', '05-03', '05-04', '05-05',
    '07-17', '08-11', '09-18', '09-23', '10-09', '11-03', '11-23'],
  2024: ['01-01', '01-08', '02-11', '02-12', '02-23', '03-20', '04-29', '05-03', '05-04', '05-05',
    '05-06', '07-15', '08-11', '08-12', '09-16', '09-22', '09-23', '10-14', '11-03', '11-04', '11-23'],
  2025: ['01-01', '01-13', '02-11', '02-23', '02-24', '03-20', '04-29', '05-03', '05-04', '05-05',
    '05-06', '07-21', '08-11', '09-15', '09-23', '10-13', '11-03', '11-23', '11-24'],
  2026: ['01-01', '01-12', '02-11', '02-23', '03-20', '04-29', '05-03', '05-04', '05-05', '05-06',
    '07-20', '08-11', '09-21', '09-22', '09-23', '10-12', '11-03', '11-23'],
  2027: ['01-01', '01-11', '02-11', '02-23', '03-21', '03-22', '04-29', '05-03', '05-04', '05-05',
    '07-19', '08-11', '09-20', '09-23', '10-11', '11-03', '11-23'],
}

function daysOf(year: number): string[] {
  const days: string[] = []
  for (let d = new Date(Date.UTC(year, 0, 1)); d.getUTCFullYear() === year; d.setUTCDate(d.getUTCDate() + 1)) {
    days.push(d.toISOString().slice(0, 10))
  }
  return days
}

describe('isJpHoliday', () => {
  it.each(Object.keys(OFFICIAL).map(Number))('%i 年の祝日・休日が内閣府の一覧と 1 日も違わない', (year) => {
    const holidays = daysOf(year).filter((ymd) => {
      const [y, m, d] = ymd.split('-').map(Number)
      return isJpHoliday(y, m, d)
    })
    expect(holidays.map((ymd) => ymd.slice(5))).toEqual(OFFICIAL[year])
  })
})
